const { isValidSudoku } = require('../leetcode/validsudoku');

describe('isValidSudoku', () => {
  test('valid board should return true', () => {
    const board = [
      ['5','3','.','.','7','.','.','.','.'],
      ['6','.','.','1','9','5','.','.','.'],
      ['.','9','8','.','.','.','.','6','.'],
      ['8','.','.','.','6','.','.','.','3'],
      ['4','.','.','8','.','3','.','.','1'],
      ['7','.','.','.','2','.','.','.','6'],
      ['.','6','.','.','.','.','2','8','.'],
      ['.','.','.','4','1','9','.','.','5'],
      ['.','.','.','.','8','.','.','7','9']
    ];

    expect(isValidSudoku(board)).toBe(true);
  });

  test('row duplicate should return false', () => {
    const board = [
      ['5','3','5','.','7','.','.','.','.'],
      ['6','.','.','1','9','5','.','.','.'],
      ['.','9','8','.','.','.','.','6','.'],
      ['8','.','.','.','6','.','.','.','3'],
      ['4','.','.','8','.','3','.','.','1'],
      ['7','.','.','.','2','.','.','.','6'],
      ['.','6','.','.','.','.','2','8','.'],
      ['.','.','.','4','1','9','.','.','5'],
      ['.','.','.','.','8','.','.','7','9']
    ];

    expect(isValidSudoku(board)).toBe(false);
  });

  test('column duplicate should return false', () => {
    const board = [
      ['5','3','.','.','7','.','.','.','.'],
      ['6','.','.','1','9','5','.','.','.'],
      ['6','9','8','.','.','.','.','6','.'],
      ['8','.','.','.','6','.','.','.','3'],
      ['4','.','.','8','.','3','.','.','1'],
      ['7','.','.','.','2','.','.','.','6'],
      ['.','6','.','.','.','.','2','8','.'],
      ['.','.','.','4','1','9','.','.','5'],
      ['.','.','.','.','8','.','.','7','9']
    ];

    expect(isValidSudoku(board)).toBe(false);
  });

  test('box duplicate should return false', () => {
    const board = [
      ['5','3','.','.','7','.','.','.','.'],
      ['6','.','3','1','9','5','.','.','.'],
      ['.','9','8','.','.','.','.','6','.'],
      ['8','.','.','.','6','.','.','.','3'],
      ['4','.','.','8','.','3','.','.','1'],
      ['7','.','.','.','2','.','.','.','6'],
      ['.','6','.','.','.','.','2','8','.'],
      ['.','.','.','4','1','9','.','.','5'],
      ['.','.','.','.','8','.','.','7','9']
    ];

    expect(isValidSudoku(board)).toBe(false);
  });

  test('sparse single-entry board should return true', () => {
    const board = Array.from({ length: 9 }, () => Array.from({ length: 9 }, () => '.'));
    board[3][4] = '1';

    expect(isValidSudoku(board)).toBe(true);
  });
});
